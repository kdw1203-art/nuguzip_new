-- 41430 라벨 정정(20260727070541)이 드러낸 뒷정리.
--
-- 41430 은 원래 큐레이션 71행에 scope='metro' 로 들어 있던 행이고,
-- display_name='시흥시' · lat/lng = 37.38 / 126.8029 를 달고 있었다.
-- 그 좌표는 **시흥시청 근처**다 — 즉 이 행은 "시흥시를 잘못된 코드에
-- 넣어 둔 것" 이었다. 이름만 의왕시로 고치고 두면 지도에서 의왕시가
-- 시흥시 자리에 찍힌다. 틀린 이름을 틀린 좌표로 바꿔 놓는 셈이라
-- 고치기 전보다 나빠진다.
--
-- 그래서 두 가지를 한다.
--  1) 검증된 시흥시 좌표를 **맞는 코드 41390** 으로 옮기고 scope 도 metro 로
--     맞춘다. 41390 은 전국 시드로 들어와 lat/lng 가 NULL 이었다.
--  2) 41430(의왕시)의 좌표는 지어내지 않는다. complex_geocode 에 실제 주소로
--     지오코딩된 **의왕시 단지 102곳**이 있어 그 중심(37.3590 / 126.9741)을
--     쓴다 — 추정값이 아니라 적재된 좌표에서 계산한 값이다.
--     (참고: 같은 방식으로 계산한 시흥시 327곳의 중심은 37.3919 / 126.7831 로,
--      위 큐레이션 좌표가 시흥시의 것이었음을 교차 확인해 준다.)

update public.legal_regions
   set scope = 'metro',
       lat = 37.38,
       lng = 126.8029,
       updated_at = now()
 where lawd_cd = '41390';

update public.legal_regions
   set display_name = '경기 의왕시',
       lat = 37.3590,
       lng = 126.9741,
       updated_at = now()
 where lawd_cd = '41430';
