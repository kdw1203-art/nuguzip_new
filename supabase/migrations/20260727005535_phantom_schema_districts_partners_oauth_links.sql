/* districts · district_snapshots 는 공개 참조 자료 — 읽기만 연다. */
do $$ begin
  if not exists (select 1 from pg_policies
                 where schemaname='public' and tablename='districts'
                   and policyname='districts_public_read') then
    create policy districts_public_read on public.districts
      for select to anon, authenticated using (true);
  end if;
  if not exists (select 1 from pg_policies
                 where schemaname='public' and tablename='district_snapshots'
                   and policyname='district_snapshots_public_read') then
    create policy district_snapshots_public_read on public.district_snapshots
      for select to anon, authenticated using (true);
  end if;
  /* 매물은 게시 중인 것만 공개한다. */
  if not exists (select 1 from pg_policies
                 where schemaname='public' and tablename='partner_listings'
                   and policyname='partner_listings_public_read_active') then
    create policy partner_listings_public_read_active on public.partner_listings
      for select to anon, authenticated using (status = 'active');
  end if;
  if not exists (select 1 from pg_policies
                 where schemaname='public' and tablename='nearby_provider_links'
                   and policyname='nearby_provider_links_public_read') then
    create policy nearby_provider_links_public_read on public.nearby_provider_links
      for select to anon, authenticated using (true);
  end if;
end $$;

