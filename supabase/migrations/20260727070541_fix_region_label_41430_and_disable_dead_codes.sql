-- 왜 이 마이그레이션이 필요한가 (docs/owner-report-region-codes.md 의 1·2번 결론)
--
-- 1) lawd_cd 41430 은 국토교통부 법정동코드상 **의왕시**인데 legal_regions 에는
--    "시흥시"로 적혀 있었다. 시흥시의 올바른 코드는 41390(8,764건)이고,
--    41430 으로 적재된 3,198건은 market_transactions.region_name 이 이미
--    "의왕시"다. 두 코드 사이에 중복 거래는 0건 — 즉 옛 코드/새 코드 쌍이
--    아니라 순수한 **라벨 오류**다. 이대로 두면 "옛 코드니까 지우자"는
--    판단이 나올 수 있고, 그러면 의왕시 실거래 수집 경로가 통째로 사라진다.
--    legal_regions 에 다른 의왕시 행은 없으므로 이름만 고치면 중복도 없다.
--
-- 2) 아래 13개 코드는 수집기가 매번 호출하지만 **한 번도 응답한 적이 없다**
--    (각 코드의 own_tx = 0). 전부 구(區)를 가진 시의 상위 코드이거나
--    (수원 41110, 성남 41130, 안양 41170, 부천 41190, 안산 41270,
--     고양 41280, 용인 41460, 청주 43110, 천안 44130, 포항 47110,
--     창원 48120, 전주 52110) 재편으로 대체된 옛 코드(전주 완산구 45111)다.
--    실제 거래는 전부 하위 구 코드로 들어온다 — 수원 22,866건, 용인 20,029건,
--    고양 18,115건, 전주 완산구는 52111 로 9,051건. 그래서 이 13개를 끄면
--    빠지는 데이터는 0건이고, ETL 왕복만 매 회차 13번 줄어든다.
--
-- 삭제는 하지 않는다(추가 전용 원칙). enabled=false 로 꺼 두기만 해서
-- 나중에 국토교통부가 상위 코드에 응답하기 시작하면 한 줄로 되돌릴 수 있다.

update public.legal_regions
   set sigungu = '의왕시',
       updated_at = now()
 where lawd_cd = '41430'
   and sigungu = '시흥시';

update public.legal_regions
   set enabled = false,
       updated_at = now()
 where lawd_cd in (
         '41110','41130','41170','41190','41270','41280','41460',
         '43110','44130','47110','48120','52110','45111'
       )
   and enabled = true;
